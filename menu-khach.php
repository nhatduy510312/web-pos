<script>
(function () {
  const search = document.getElementById('menu-search');
  const clear = document.getElementById('clear-search');
  const sections = Array.from(document.querySelectorAll('.menu-section'));
  const count = document.getElementById('result-count');
  const empty = document.getElementById('empty-state');

  const normalize = (value) => value
    .toLocaleLowerCase('vi')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd');

  function filterMenu() {
    const query = normalize(search.value.trim());
    let visibleTotal = 0;

    sections.forEach((section) => {
      const items = Array.from(section.querySelectorAll('.menu-item'));
      let visibleInSection = 0;

      items.forEach((item) => {
        const matches = !query || normalize(item.dataset.search || '').includes(query);
        item.hidden = !matches;
        if (matches) visibleInSection += 1;
      });

      section.hidden = visibleInSection === 0;
      const badge = section.querySelector('.section-count');
      badge.textContent = String(visibleInSection);
      badge.setAttribute('aria-label', visibleInSection + ' món');
      visibleTotal += visibleInSection;
    });

    clear.hidden = !search.value;
    empty.style.display = visibleTotal === 0 ? 'block' : 'none';
    count.textContent = query ? 'Tìm thấy ' + visibleTotal + ' món phù hợp' : '';
  }

