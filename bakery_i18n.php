function bakeryT(string $text): string
{
    if (bakeryLanguage() !== 'en') return $text;
    return bakeryTranslations()[$text] ?? $text;
}

function bakeryLanguageUrl(string $language): string
{
    $query = $_GET;
    $query['lang'] = $language;
    return bakeryH(basename((string)($_SERVER['PHP_SELF'] ?? 'bakery.php')) . '?' . http_build_query($query));
}

function bakeryLanguageSwitcher(string $class = ''): string
{
    $language = bakeryLanguage();
    return '<div class="bk-language ' . bakeryH($class) . '" aria-label="Language">'
        . '<a class="' . ($language === 'vi' ? 'active' : '') . '" href="' . bakeryLanguageUrl('vi') . '">VI</a>'
        . '<a class="' . ($language === 'en' ? 'active' : '') . '" href="' . bakeryLanguageUrl('en') . '">EN</a></div>';
}

function bakeryTranslationScript(): string
{
    if (bakeryLanguage() !== 'en') return '';
    $dictionary = json_encode(bakeryTranslations(), JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT);
    return '<script>(function(){const d=' . $dictionary . ',keys=Object.keys(d).sort((a,b)=>b.length-a.length);function tr(v){const s=v.trim();if(d[s])return v.replace(s,d[s]);return v.replace(/Tổng ghi nhận:/g,"Recorded total:").replace(/ — tồn /g," — stock ").replace(/ · SL /g," · Qty ")}function attr(v){let r=tr(v);for(const k of keys){if(r.includes(k))r=r.split(k).join(d[k])}return r}function run(){document.documentElement.lang="en";document.title=d[document.title]||document.title;const w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);const nodes=[];while(w.nextNode()){const p=w.currentNode.parentElement;if(p&&!/^(SCRIPT|STYLE|TEXTAREA)$/.test(p.tagName)&&w.currentNode.nodeValue.trim())nodes.push(w.currentNode)}nodes.forEach(n=>n.nodeValue=tr(n.nodeValue));document.querySelectorAll("[placeholder],[title],[aria-label],[onsubmit]").forEach(e=>["placeholder","title","aria-label","onsubmit"].forEach(a=>{const v=e.getAttribute(a);if(v)e.setAttribute(a,attr(v))}))}if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",run);else run()})()</script>';
}
